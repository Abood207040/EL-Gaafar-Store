const LocalizationContext = createContext(null);

export function LocalizationProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try {
      return window.localStorage.getItem(STORAGE_KEY) || 'ar';
    } catch {
      return 'ar';
    }
  });

  useEffect(() => {
    const dir = language === 'ar' ? 'rtl' : 'ltr';
    document.documentElement.lang = language;
    document.documentElement.dir = dir;
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // Ignore storage errors in restricted environments.
    }
  }, [language]);

  const value = useMemo(() => {
    const isArabic = language === 'ar';
    const t = (key, ...args) => {
      const entry = messages[language]?.[key] ?? messages.en[key] ?? key;
      return typeof entry === 'function' ? entry(...args) : entry;
    };

    const translateCategory = (category) =>
      isArabic ? CATEGORY_LABELS[category] || category : category;
    const translateStock = (status) =>
      isArabic ? STOCK_LABELS[status] || status : status;
    const translateOrderStatus = (status) =>
      isArabic ? ORDER_LABELS[status] || status : status;
    const translateFulfillment = (method) =>
      isArabic ? FULFILLMENT_LABELS[method] || method : method;
    const translateSpecLabel = (label) =>
      isArabic ? SPEC_LABELS[label] || SPEC_KEY_LABELS[label] || label : label;
    const translateSpecValue = (value) =>
      isArabic ? SPEC_VALUE_AR[value] || value : value;
    const productName = (product) => (isArabic ? product.nameAr || product.nameEn : product.nameEn);
    const productAltName = (product) => (isArabic ? product.nameEn : product.nameAr);
    const productDescription = (product) =>
      isArabic
        ? product.descriptionAr || PRODUCT_DESCRIPTIONS_AR[product.id] || product.descriptionEn || product.description
        : product.descriptionEn || product.description;
    const customerStatus = (status) => {
      const key = {
        Active: 'customerStatusActive',
        New: 'customerStatusNew',
        Inactive: 'customerStatusInactive',
      }[status];
      return key ? t(key) : status;
    };
    const timelineStep = (step) => {
      const key = {
        Placed: 'timelinePlaced',
        Confirmed: 'timelineConfirmed',
        Processing: 'timelineProcessing',
        Shipped: 'timelineShipped',
        'Ready for Pickup': 'timelineReady',
        Delivered: 'timelineDelivered',
        Cancelled: 'timelineCancelled',
      }[step];
      return key ? t(key) : step;
    };

    const parseRpcError = (error) => {
      if (!error || !error.message) return t('ERR_UNKNOWN');
      
      try {
        const parsed = JSON.parse(error.message);
        if (parsed && parsed.code) {
          // If we have a translation for this code, use it.
          // Fallback to the message from the server if no translation.
          const translated = t(parsed.code);
          if (translated !== parsed.code) {
            // Include details if it's an insufficient stock error for a specific product
            if (parsed.code === 'ERR_INSUFFICIENT_STOCK' && parsed.details?.productName) {
              return isArabic 
                ? `لا يوجد مخزون كافٍ لمنتج: ${parsed.details.productName} (المطلوب: ${parsed.details.requested}، المتاح: ${parsed.details.available})`
                : `Insufficient stock for: ${parsed.details.productName} (Requested: ${parsed.details.requested}, Available: ${parsed.details.available})`;
            }
            if (parsed.code === 'ERR_NOT_AVAILABLE' && parsed.details?.productName) {
              return isArabic
                ? `المنتج غير متاح للبيع: ${parsed.details.productName}`
                : `Product not available for sale: ${parsed.details.productName}`;
            }
            return translated;
          }
          return parsed.message || t('ERR_UNKNOWN');
        }
      } catch {
        // Not a JSON error, handle legacy string errors if needed
        const msg = error.message.toLowerCase();
        if (msg.includes('insufficient stock')) return t('ERR_INSUFFICIENT_STOCK');
        if (msg.includes('not available')) return t('ERR_NOT_AVAILABLE');
        if (msg.includes('not found')) return t('ERR_NOT_FOUND');
      }
      
      return error.message;
    };

    return {
      language,
      dir: isArabic ? 'rtl' : 'ltr',
      isArabic,
      setLanguage,
      toggleLanguage: () => setLanguage((current) => (current === 'ar' ? 'en' : 'ar')),
      t,
      translateCategory,
      translateStock,
      translateOrderStatus,
      translateFulfillment,
      translateSpecLabel,
      translateSpecValue,
      productName,
      productAltName,
      productDescription,
      customerStatus,
      timelineStep,
      parseRpcError,
    };
  }, [language]);

  return (
    <LocalizationContext.Provider value={value}>
      {children}
    </LocalizationContext.Provider>
  );
}

// eslint-disable-next-line react-refresh/only-export-components
export function useLocalization() {
  const context = useContext(LocalizationContext);
  if (!context) {
    throw new Error('useLocalization must be used inside LocalizationProvider');
  }
  return context;
}
